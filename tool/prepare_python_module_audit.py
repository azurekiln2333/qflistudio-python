"""Generate an ignored Dart entry from the portable embedded behavior suite.

This only prepares build inputs. It does not execute Python acceptance, build a
HAP, or access a device. Run the generated entry for actual runtime evidence.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

try:
    from .python_audit_inputs import collect_inputs
except ImportError:
    from python_audit_inputs import collect_inputs


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def dart_string(value: str) -> str:
    # JSON escapes are valid Dart string escapes; Dart also interpolates '$'.
    return json.dumps(value, ensure_ascii=True).replace("$", r"\$")


def prepare(root: Path, output: Path, native_library: Path | None, build_metadata: dict | None = None) -> dict:
    root = root.resolve()
    output = output.resolve()
    if root not in output.parents or output == root:
        raise ValueError("Generated audit files must stay inside this project")
    if root / "build" not in (output, *output.parents):
        raise ValueError("Generated audit files must stay in ignored build/")
    suite_file = root / "native/tests/python_stdlib_smoke.py"
    suite_bytes = suite_file.read_bytes()
    suite = suite_bytes.decode("utf-8")
    assets_root = root / "assets/python_stdlib"
    manifest = json.loads((assets_root / "manifest.json").read_bytes())
    modules = manifest["modules"]
    if len(modules) < 10:
        raise ValueError("Acceptance requires at least ten bundled modules")
    for module in modules:
        for entry in module["files"]:
            path = assets_root / entry["path"]
            if assets_root.resolve() not in path.resolve().parents:
                raise ValueError(f"Manifest file escapes bundle: {entry['path']}")
            if digest(path.read_bytes()) != entry["sha256"]:
                raise ValueError(f"Bundle digest mismatch: {entry['path']}")
    assets = {
        path.relative_to(root).as_posix(): digest(path.read_bytes())
        for path in sorted(assets_root.rglob("*"))
        if path.is_file()
    }
    evidence = {
        "suiteSource": suite_file.relative_to(root).as_posix(),
        "suiteSha256": digest(suite_bytes),
        "bundleVersion": manifest["bundleVersion"],
        "bundledModuleNames": sorted(module["name"] for module in modules),
        "assetDigests": assets,
        "sourceDigests": {
            name: digest((root / name).read_bytes())
            for name in (
                "tool/python_module_ohos_audit.dart",
                "lib/python_runner.dart",
                "lib/python_runtime_activity.dart",
                "lib/python_ffi.dart",
                "lib/python_native_library.dart",
                "lib/python_packages.dart",
                "lib/python_module_catalog.dart",
                "native/ohos/QfliPyNative.ets",
                "ohos/entry/src/main/ets/plugins/QfliPyNative.ets",
                "ohos/entry/src/main/ets/entryability/EntryAbility.ets",
                "ohos/entry/src/main/ets/pages/Index.ets",
            )
        },
        "nativeLibrary": None,
        "buildMetadata": build_metadata or {},
    }
    evidence["sourceDigests"], evidence["coreSourceDigests"] = collect_inputs(root, root.parent / "qfli_studio_core")
    if native_library is not None:
        native_library = native_library.resolve()
        native_bytes = native_library.read_bytes()
        if len(native_bytes) < 20 or native_bytes[:6] != b"\x7fELF\x02\x01" or int.from_bytes(native_bytes[18:20], "little") != 62:
            raise ValueError("The audit native library must be ELF64 x86_64")
        evidence["nativeLibrary"] = {
            "path": native_library.relative_to(root).as_posix(),
            "sha256": digest(native_bytes),
            "bytes": len(native_bytes),
            "abi": "x86_64",
            "evidenceKind": "declared-build-input; independently checked against HAP",
        }
    output.mkdir(parents=True, exist_ok=True)
    (output / "suite.g.dart").write_text(
        "// Generated by tool/prepare_python_module_audit.py. Do not edit.\n"
        f"const pythonAuditSuite = {dart_string(suite)};\n"
        f"const pythonAuditSuiteSha256 = {dart_string(digest(suite_bytes))};\n"
        "const pythonAuditAssetDigests = <String, String>{\n"
        + "".join(f"  {dart_string(name)}: {dart_string(value)},\n" for name, value in assets.items())
        + "};\n"
        + f"const pythonAuditBuildEvidenceJson = {dart_string(json.dumps(evidence, sort_keys=True))};\n",
        encoding="utf-8",
        newline="\n",
    )
    # Relative imports are derived from the output location, never assumed to be
    # a fixed nesting depth. No generated source is added to the product tree.
    import os

    harness = os.path.relpath(root / "tool/python_module_ohos_audit.dart", output).replace("\\", "/")
    (output / "main.dart").write_text(
        "// Generated audit-only entry; normal lib/main.dart remains untouched.\n"
        "import 'dart:convert';\n"
        f"import {dart_string(harness)};\n"
        "import 'suite.g.dart';\n"
        "void main() => startPythonModuleAudit(\n"
        "  suiteSource: pythonAuditSuite,\n"
        "  suiteSha256: pythonAuditSuiteSha256,\n"
        "  assetDigests: pythonAuditAssetDigests,\n"
        "  buildEvidence: (jsonDecode(pythonAuditBuildEvidenceJson) as Map<String, dynamic>),\n"
        ");\n",
        encoding="utf-8",
        newline="\n",
    )
    (output / "inputs.json").write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8", newline="\n")
    return evidence


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="build/python_module_audit")
    parser.add_argument("--native-library", help="Existing x86_64 SO to bind to the eventual HAP")
    parser.add_argument("--build-metadata", type=Path, help="Declared invocation identity; independently checked in the packaged kernel")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    output = Path(args.output)
    if not output.is_absolute():
        output = root / output
    native = Path(args.native_library) if args.native_library else None
    if native is not None and not native.is_absolute():
        native = root / native
    metadata = json.loads(args.build_metadata.read_bytes()) if args.build_metadata else {}
    if not isinstance(metadata, dict):
        parser.error("--build-metadata must contain a JSON object")
    evidence = prepare(root, output, native, metadata)
    print(json.dumps({"entry": str(output / "main.dart"), "suiteSha256": evidence["suiteSha256"], "assetCount": len(evidence["assetDigests"])}))


if __name__ == "__main__":
    main()
